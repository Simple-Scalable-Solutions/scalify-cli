# Writes internal/mcp/code_orch_meta.go: each endpoint's params (path, query, body) from spec.json,
# so scalify_search can show them and scalify_execute knows which params go in the query string.
import json,re,sys
spec=json.load(open(sys.argv[1])); out=sys.argv[2]
sch=spec["components"]["schemas"]
def resolve(s):
    while isinstance(s,dict) and "$ref" in s: s=sch[s["$ref"].split("/")[-1]]
    return s or {}
def typ(s):
    s=resolve(s)
    if "type" in s: return s["type"]
    for k in ("oneOf","anyOf","allOf"):
        if k in s: return "object"
    return "any"
def q(x): return json.dumps(x)
def gl(xs): return "[]string{"+", ".join(json.dumps(x) for x in xs)+"}"
rows=[]
for p,ops in sorted(spec["paths"].items()):
    for m,op in sorted(ops.items()):
        params=op.get("parameters",[])
        path=re.findall(r"{(\w+)}",p)
        query=[]
        for x in params:
            if x.get("in")!="query": continue
            query.append(x["name"]+("*" if x.get("required") else "")+":"+typ(x.get("schema",{})))
        body=[]
        rb=resolve(op.get("requestBody",{}).get("content",{}).get("application/json",{}).get("schema",{}))
        req=set(rb.get("required",[]))
        for name,ps in rb.get("properties",{}).items():
            body.append(name+("*" if name in req else "")+":"+typ(ps))
        rows.append(f'\t{q(m.upper()+" "+p)}: {{Path: {gl(path)}, Query: {gl(query)}, Body: {gl(body)}}},')
go="""// Code generated by scripts/regen/gen_orch_meta.py from spec.json. DO NOT EDIT.

package mcp

// codeOrchMeta lists each endpoint's params, keyed by "METHOD /path". A trailing * marks a
// required param; the suffix after the colon is its JSON type.
var codeOrchMeta = map[string]codeOrchParams{
"""+"\n".join(rows)+"\n}\n"
open(out,"w").write(go)
print("orch meta:",len(rows),"endpoints")
